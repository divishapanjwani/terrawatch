"""Field report: one-click PDF + mobile-friendly HTML, built from
already-computed analysis results only -- no LLM call, no invented
facts. Every value in build_context() traces back to a column already
on the Analysis row or a kept-polygon GeoJSON feature; render_html()
only ever inserts those values (plus static, hand-written i18n strings
from app/reports/i18n.py) into the template.
"""

import base64
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from PIL import Image

from app.reports.i18n import get_translations

SNAPSHOT_MAX_WIDTH = 720
TOP_N = 10


def _fmt(n, decimals=0) -> Optional[str]:
    if n is None:
        return None
    return f"{n:,.{decimals}f}"


def _localized_reason(p: dict, t: dict) -> str:
    """Rebuilds the priority_reason sentence in the report's language from
    the underlying computed values (severity, population, nearest
    facility, route_impact) -- app/pipeline/priority.py's _build_reason()
    computes the same sentence in English only, so this can't just reuse
    that string for hi/mr. Every value inserted is already on the
    polygon; only the surrounding phrase templates are translated
    (app/reports/i18n.py), never generated by an LLM."""
    parts = []
    severity = p.get("severity")
    sev_label = t["severity_label"].get(severity, severity or "—")
    parts.append(t["reason_severity"].format(severity=sev_label))

    pop = p.get("population_buffer_est")
    if pop is not None and pop >= 1:
        parts.append(t["reason_people"].format(n=round(pop)))

    candidates = []
    if p.get("nearest_hospital_m") is not None:
        candidates.append((p["nearest_hospital_m"], "hospital"))
    if p.get("nearest_school_m") is not None:
        candidates.append((p["nearest_school_m"], "school"))
    if candidates:
        dist, kind = min(candidates, key=lambda c: c[0])
        key = "reason_facility_hospital" if kind == "hospital" else "reason_facility_school"
        parts.append(t[key].format(dist=f"{dist:.0f}"))

    route_impact = p.get("route_impact")
    if route_impact == "no_alternative":
        parts.append(t["reason_route_no_alt"].format(blockage_note=t["blockage_note"]))
    elif route_impact == "detour" and p.get("detour_m") is not None:
        parts.append(
            t["reason_route_detour"].format(detour=f"{p['detour_m']:.0f}", blockage_note=t["blockage_note"])
        )

    sentence = "; ".join(parts) + "."
    if p.get("in_hazard_zone"):
        sentence = f"{t['hazard_zone_wording']}. {sentence}"
    return sentence


def _embed_image_data_uri(png_path: str) -> str:
    img = Image.open(png_path).convert("RGB")
    if img.width > SNAPSHOT_MAX_WIDTH:
        scale = SNAPSHOT_MAX_WIDTH / img.width
        img = img.resize((SNAPSHOT_MAX_WIDTH, max(1, int(img.height * scale))), Image.LANCZOS)
    import io

    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=78)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode("ascii")


def build_context(analysis, kept_features: list, lang: str, snapshot_path: str) -> dict:
    """analysis: the Analysis DB row. kept_features: GeoJSON Feature
    dicts (EPSG:4326) with status == "kept" from the saved export."""
    t = get_translations(lang)
    area_changed_km2 = sum(f["properties"].get("area_m2", 0.0) for f in kept_features) / 1e6

    top = sorted(kept_features, key=lambda f: (f["properties"].get("priority_rank") or 10**9))[:TOP_N]
    rows = []
    for f in top:
        p = f["properties"]
        lat, lon = p.get("centroid_lat"), p.get("centroid_lon")
        route_impact = p.get("route_impact")
        rank = p.get("priority_rank")
        rows.append(
            {
                "rank": int(rank) if rank is not None else "—",
                "type": t["change_type"].get(p.get("change_type"), p.get("change_type") or "—"),
                "area_m2": _fmt(p.get("area_m2")) or "—",
                "people": _fmt(p.get("population_buffer_est")) if p.get("population_buffer_est") else t["no_data"],
                "hospital": (
                    f"{p['nearest_hospital_name']} ({_fmt(p['nearest_hospital_m'])} m)"
                    if p.get("nearest_hospital_name")
                    else t["no_data"]
                ),
                "route": t["route_impact"].get(route_impact, "—") if route_impact else "—",
                "reason": _localized_reason(p, t),
                "gmaps": f"https://www.google.com/maps?q={lat},{lon}" if lat is not None else None,
            }
        )

    return {
        "t": t,
        "lang": lang,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "engine": analysis.engine or "—",
        "analysis_id": analysis.id,
        "kept_count": analysis.kept_count,
        "rejected_count": analysis.rejected_count,
        "area_changed_km2": f"{area_changed_km2:.1f}",
        "people_estimate": _fmt(analysis.total_population_buffer_est) if analysis.total_population_buffer_est else t["no_data"],
        "near_facility_count": analysis.near_facility_count if analysis.near_facility_count is not None else "—",
        "snapshot_data_uri": _embed_image_data_uri(snapshot_path) if Path(snapshot_path).exists() else None,
        "rows": rows,
    }


